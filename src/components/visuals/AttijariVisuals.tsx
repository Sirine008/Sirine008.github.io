import { Bars, type BarRow } from '../viz/Bars'
import { TableView, VizBlock } from '../viz/VizBlock'

const CARD = 'https://github.com/Sirine008/attendance-dashboard-ml/blob/main/ml-service/reports/model_card.md'

/** PR-AUC from the model card (version v20261028-155209), real data only. */
const RESULTS = {
  d1: {
    label: 'Next working day',
    rows: [
      { name: 'Weekday-rate baseline', val: 0.162, test: 0.135, used: true, baseline: true },
      { name: 'LightGBM', val: 0.152, test: 0.124 },
      { name: 'Logistic regression', val: 0.108, test: 0.193 },
      { name: 'Historical-rate baseline', val: 0.091, test: 0.067, baseline: true },
    ],
  },
  w1: {
    label: 'Next five working days',
    rows: [
      { name: 'Weekday-rate baseline', val: 0.311, test: 0.27, used: true, baseline: true },
      { name: 'Historical-rate baseline', val: 0.304, test: 0.279, baseline: true },
      { name: 'LightGBM', val: 0.225, test: 0.301 },
      { name: 'Logistic regression', val: 0.204, test: 0.173 },
    ],
  },
} as const

type Row = { name: string; val: number; test: number; used?: boolean; baseline?: boolean }

const toBars = (rows: readonly Row[]): BarRow[] =>
  rows.map((r) => ({
    label: r.name,
    value: r.val,
    tone: r.used ? 'accent' : 'muted',
    note: [r.baseline ? 'baseline' : '', r.used ? 'used — best on validation' : ''].filter(Boolean).join(' · ') || undefined,
  }))

const f3 = (v: number) => v.toFixed(3)

export function AttijariVisuals() {
  return (
    <VizBlock
      id="att-selection"
      kicker="Model selection · real data"
      title="On validation, the simple rule comes first"
      lead={
        <p>
          Precision–recall AUC on the monthly walk-forward validation (July–December 2024), the only scores used to choose.
          Higher is better; a random guess scores about the share of absence days. The highlighted bars are the rule that now
          produces the estimates.
        </p>
      }
      source={{ text: 'model card generated by the training pipeline.', href: CARD, label: 'model_card.md' }}
    >
      <p className="mono viz-kicker">{RESULTS.d1.label}</p>
      <Bars label="Validation PR-AUC, next working day" max={0.2} format={f3} rows={toBars(RESULTS.d1.rows)} />
      <p className="mono viz-kicker" style={{ marginTop: '1.5rem' }}>
        {RESULTS.w1.label}
      </p>
      <Bars label="Validation PR-AUC, next five working days" max={0.36} format={f3} rows={toBars(RESULTS.w1.rows)} />
      <TableView
        caption="Validation and 2025 test PR-AUC for each predictor and horizon"
        head={['Predictor', 'Horizon', 'Validation', 'Test 2025']}
        rows={[
          ...RESULTS.d1.rows.map((r) => [r.name, 'Next day', f3(r.val), f3(r.test)]),
          ...RESULTS.w1.rows.map((r) => [r.name, 'Next week', f3(r.val), f3(r.test)]),
        ]}
      />
    </VizBlock>
  )
}
